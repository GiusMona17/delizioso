    /** Curated Italian ingredient names sorted alphabetically with title casing. */
    val ALL_ITALIAN_INGREDIENTS: List<String> = IT_TO_EN.keys
        .map { it.replaceFirstChar(Char::titlecase) }
        .distinct()
        .sorted()

    /**
     * Translates an Italian ingredient or dish name to English for international providers (TheMealDB, etc.).
     * If no exact match is found, attempts substring match or returns the original term.
     */
    fun toEnglish(italianTerm: String): String {
        val trimmed = italianTerm.trim().lowercase()
        IT_TO_EN[trimmed]?.let { return it }

        for ((itKey, enVal) in IT_TO_EN) {
            if (trimmed == itKey || trimmed.contains(itKey)) {
                return enVal
            }
        }

        return italianTerm.trim()
    }
